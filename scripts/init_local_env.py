"""Create the local configuration for the Compose stack, if it does not exist yet.

Writes ``.env`` with random database passwords and ``secrets/api_keys.json`` with one demo key
(all scopes, 90 days). There are no fixed default credentials [BSI DEV.4.8, KONF.10.3]. The demo
token is stored in ``secrets/demo_api_key`` (gitignored) so ``make smoke`` can use it; it is a
local development credential only.
"""

from __future__ import annotations

import json
import secrets
import sys
from pathlib import Path

from titanic_mcp.auth import Scope, entry_to_json, generate_key

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".env"
SECRETS_DIR = ROOT / "secrets"


def main() -> int:
    """Create missing files; never overwrite existing ones."""
    if not ENV_FILE.exists():
        passwords = {name: secrets.token_urlsafe(24) for name in ("OWNER", "APP", "SQL")}
        ENV_FILE.write_text(
            "\n".join(
                [
                    "# Generated by scripts/init_local_env.py for the local Compose stack.",
                    f"TMCP_DB_OWNER_PASSWORD={passwords['OWNER']}",
                    f"TMCP_DB_APP_PASSWORD={passwords['APP']}",
                    f"TMCP_DB_SQL_PASSWORD={passwords['SQL']}",
                    "",
                ]
            )
        )
        sys.stdout.write("Created .env with random database passwords.\n")
    SECRETS_DIR.mkdir(exist_ok=True)
    keys_file = SECRETS_DIR / "api_keys.json"
    if not keys_file.exists():
        key = generate_key(
            agent="local-demo", team="local", scopes={Scope.READ, Scope.PII, Scope.SQL}, days=90
        )
        keys_file.write_text(json.dumps([entry_to_json(key.entry)], indent=2) + "\n")
        (SECRETS_DIR / "demo_api_key").write_text(key.token + "\n")
        sys.stdout.write(f"Created demo API key (stored in secrets/demo_api_key): {key.token}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
